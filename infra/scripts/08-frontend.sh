#!/usr/bin/env bash
# 08-frontend.sh (owner: Jomana)
# The website bucket is PUBLIC, so ONLY the static frontend goes in it.
# We upload with an ALLOW-list (*.html, css/, js/) - never backend/, .env, *.zip.
# The API URL and Cognito ids are written to js/env.js at deploy time (not secrets).
source "$(dirname "$0")/00-env.sh"
: "${API_URL:?run 06-api-gateway.sh first}"

log "Website bucket $WEB_BUCKET"
aws s3api head-bucket --bucket "$WEB_BUCKET" 2>/dev/null || aws s3api create-bucket --bucket "$WEB_BUCKET" >/dev/null
# New buckets block public access by default (real AWS and Floci). We allow a public
# READ policy on THIS bucket only; ACLs stay blocked.
aws s3api put-public-access-block --bucket "$WEB_BUCKET" --public-access-block-configuration \
  BlockPublicAcls=true,IgnorePublicAcls=true,BlockPublicPolicy=false,RestrictPublicBuckets=false
[ "$TARGET" = "aws" ] && aws s3 website "s3://$WEB_BUCKET" --index-document index.html
POLICY="$(render_policy "$INFRA_DIR/iam/frontend-public-read.json")"
aws s3api put-bucket-policy --bucket "$WEB_BUCKET" --policy "file://$POLICY"
rm -f "$POLICY"
aws s3api put-bucket-versioning --bucket "$WEB_BUCKET" --versioning-configuration Status=Enabled || true
ok "public read (GetObject only) on $WEB_BUCKET, versioning on"

STAGE="$(mktemp -d)"
cp -R "$ROOT_DIR/frontend/." "$STAGE/"
cat > "$STAGE/js/env.js" <<JS
// Generated by infra/scripts/08-frontend.sh - public values only, no secrets.
window.LOYALTY_ENV = {
  apiUrl: '$API_URL',
  cognitoEndpoint: '$( [ "$TARGET" = floci ] && echo "http://localhost:4566" || echo "https://cognito-idp.$AWS_REGION.amazonaws.com" )',
  cognitoClientId: '$COGNITO_CLIENT_ID'
};
JS

log "Upload (allow-list only)"
aws s3 sync "$STAGE" "s3://$WEB_BUCKET" --delete \
  --exclude '*' --include '*.html' --include 'favicon.svg' --exclude '*/*' \
  --content-type 'text/html; charset=utf-8' >/dev/null
aws s3 sync "$STAGE/css" "s3://$WEB_BUCKET/css" --delete --exclude '*' --include '*.css' --content-type text/css >/dev/null
aws s3 sync "$STAGE/js" "s3://$WEB_BUCKET/js" --delete --exclude '*' --include '*.js' --content-type text/javascript >/dev/null
aws s3 cp "$STAGE/favicon.svg" "s3://$WEB_BUCKET/favicon.svg" --content-type image/svg+xml >/dev/null 2>&1 || true
rm -rf "$STAGE"

log "Bucket contents (must be ONLY html/css/js)"
aws s3 ls "s3://$WEB_BUCKET" --recursive
if aws s3 ls "s3://$WEB_BUCKET" --recursive | grep -Eq '\.env|\.zip|backend/|node_modules|package\.json'; then
  warn "Forbidden file found in the public bucket!"; exit 1
fi

if [ "$TARGET" = "floci" ]; then WEB_URL="http://localhost:4566/$WEB_BUCKET/index.html"; else WEB_URL="$FRONTEND_ORIGIN"; fi
save_output WEB_URL "$WEB_URL"
ok "Website: $WEB_URL"
